#!/usr/bin/env python3
"""Generate workflow-io-contract TypeScript from api_nodes.

Brand Brain and other consumers pin a release tag and copy ``dist/workflow-io-contract.ts``.
Run from the repo root::

    python3 scripts/generate_workflow_io_contract.py
    python3 scripts/generate_workflow_io_contract.py --check   # CI: fail if dist/ is stale
    python3 scripts/generate_workflow_io_contract.py --release v0.1.0   # header names the release
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
TS_PATH = REPO_ROOT / "dist" / "workflow-io-contract.ts"
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from api_nodes import NODE_CLASS_MAPPINGS, NODE_DISPLAY_NAME_MAPPINGS
from api_nodes.common import (
    CATEGORY_INPUT,
    CATEGORY_OUTPUT,
    META_FIELDS,
    NODE_SCHEMA,
    VALUE_TYPES,
    value_types_for,
)
from api_nodes.reframe import CROP_PURPOSES

GENERATOR_VERSION = "1"

# Exported API JSON may include these optional fields (parser → mappings → Composer).
SEMANTIC_EXPORT_FIELDS: dict[str, list[str]] = {
    "WorkflowIOIntInput": ["value_type"],
    "WorkflowIOFloatInput": ["value_type"],
    "WorkflowIOEnumInput": ["value_type"],
    "WorkflowIOMultiEnumInput": ["value_type", "separator"],
    "WorkflowIOImageVideoReframe": ["crop_purpose"],
    "WorkflowIOVideoInput": ["start_frame", "end_frame", "max_length", "max_frames"],
}


def class_types_in(category: str) -> list[str]:
    return sorted(name for name, cls in NODE_CLASS_MAPPINGS.items() if cls.CATEGORY == category)


def node_catalog() -> list[dict]:
    """One row per node, inputs first, then display name. The admin registry lists this."""
    rows = [
        {
            "classType": class_type,
            "displayName": NODE_DISPLAY_NAME_MAPPINGS[class_type],
            "role": "input" if cls.CATEGORY == CATEGORY_INPUT else "output",
            "semanticFields": SEMANTIC_EXPORT_FIELDS.get(class_type, []),
        }
        for class_type, cls in sorted(NODE_CLASS_MAPPINGS.items())
    ]
    rows.sort(key=lambda row: (row["role"] != "input", row["displayName"]))
    return rows


def ts_union(values: list[str]) -> str:
    return " | ".join(json.dumps(v) for v in values)


def render_typescript(release: str | None = None) -> str:
    input_types = class_types_in(CATEGORY_INPUT)
    # Kinds in the order VALUE_TYPES first mentions them (enum, int, float).
    kinds = dict.fromkeys(kind for kinds, _ in VALUE_TYPES.values() for kind in kinds)
    value_types = {
        name: {"kinds": list(kinds), "description": desc}
        for name, (kinds, desc) in VALUE_TYPES.items()
    }
    source = f" from release {release}" if release else ""
    lines = [
        f"/** Generated by scripts/generate_workflow_io_contract.py{source} — do not edit. */",
        "",
        f"export const WORKFLOW_IO_NODE_SCHEMA = {json.dumps(NODE_SCHEMA)} as const;",
        "",
        f"export type WorkflowIoValueType = {ts_union(list(VALUE_TYPES))};",
        *(
            f"export type WorkflowIoValueType{kind.capitalize()} = {ts_union(value_types_for(kind))};"
            for kind in kinds
        ),
        "",
        f"export type WorkflowIoCropPurpose = {ts_union(CROP_PURPOSES)};",
        "",
        f"export type WorkflowIoMetaField = {ts_union(META_FIELDS)};",
        "",
        f"export type WorkflowIoNodeClassType = {ts_union(sorted(NODE_CLASS_MAPPINGS))};",
        f"export type WorkflowIoInputClassType = {ts_union(input_types)};",
        f"export type WorkflowIoOutputClassType = {ts_union(class_types_in(CATEGORY_OUTPUT))};",
        "",
        "export const WORKFLOW_IO_VALUE_TYPES = "
        + json.dumps(value_types, indent=2)
        + " as const satisfies Record<"
        "WorkflowIoValueType, { kinds: readonly string[]; description: string }>;",
        "",
        f"export const WORKFLOW_IO_CROP_PURPOSES = {json.dumps(list(CROP_PURPOSES))} as const;",
        "",
        f"export const WORKFLOW_IO_INPUT_CLASS_TYPES = {json.dumps(input_types)} as const;",
        "",
        "/** Every Workflow IO node, in list order. Brand Brain's widget registry reads this. */",
        "export const WORKFLOW_IO_NODES = "
        + json.dumps(node_catalog(), indent=2)
        + " as const satisfies readonly {"
        " classType: WorkflowIoNodeClassType;"
        " displayName: string;"
        " role: 'input' | 'output';"
        " semanticFields: readonly string[];"
        " }[];",
        "",
        "/** Optional semantic fields a node's exported inputs may carry (api_config / mappings). */",
        "export const WORKFLOW_IO_SEMANTIC_EXPORT_FIELDS = "
        + json.dumps(SEMANTIC_EXPORT_FIELDS, indent=2)
        + " as const;",
        "",
        "export const WORKFLOW_IO_CONTRACT = "
        + json.dumps({"generatorVersion": GENERATOR_VERSION, "nodeSchema": NODE_SCHEMA}, indent=2)
        + " as const;",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit 1 if dist/workflow-io-contract.ts differs from a fresh generation",
    )
    parser.add_argument(
        "--release",
        help="Release tag to name in the file's header, e.g. v0.1.0 or alpha-<branch>",
    )
    args = parser.parse_args()

    ts_text = render_typescript(args.release)
    if args.check:
        if not TS_PATH.is_file() or TS_PATH.read_text() != ts_text:
            print(
                f"{TS_PATH.name} is stale; run: python3 scripts/generate_workflow_io_contract.py",
                file=sys.stderr,
            )
            return 1
        print("Contract output is up to date.")
        return 0

    TS_PATH.parent.mkdir(parents=True, exist_ok=True)
    TS_PATH.write_text(ts_text)
    print(f"Wrote {TS_PATH.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
