#!/usr/bin/env python3
"""Generate workflow-io-contract TypeScript from api_nodes.

Brand Brain and other consumers pin a release tag and copy ``dist/workflow-io-contract.ts``
(JSON can be added later from the same ``build_contract()`` if a non-TS consumer needs it).
Run from the repo root::

    python3 scripts/generate_workflow_io_contract.py
    python3 scripts/generate_workflow_io_contract.py --check   # CI: fail if dist/ is stale
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from api_nodes import NODE_CLASS_MAPPINGS, NODE_DISPLAY_NAME_MAPPINGS
from api_nodes.common import (
    CATEGORY_INPUT,
    CATEGORY_OUTPUT,
    META_FIELDS,
    NODE_SCHEMA,
    VALUE_TYPES,
    value_types_for,
)
from api_nodes.reframe import CROP_PURPOSES

GENERATOR_VERSION = "1"

# Exported API JSON may include these optional fields (parser → mappings → Composer).
SEMANTIC_EXPORT_FIELDS: dict[str, list[str]] = {
    "WorkflowIOIntInput": ["value_type"],
    "WorkflowIOFloatInput": ["value_type"],
    "WorkflowIOEnumInput": ["value_type"],
    "WorkflowIOMultiEnumInput": ["value_type", "separator"],
    "WorkflowIOImageVideoReframe": ["crop_purpose"],
}


def build_contract() -> dict:
    value_types = [
        {"name": name, "kinds": list(kinds), "description": desc}
        for name, (kinds, desc) in VALUE_TYPES.items()
    ]
    input_nodes = sorted(
        name for name, cls in NODE_CLASS_MAPPINGS.items() if cls.CATEGORY == CATEGORY_INPUT
    )
    output_nodes = sorted(
        name for name, cls in NODE_CLASS_MAPPINGS.items() if cls.CATEGORY == CATEGORY_OUTPUT
    )
    return {
        "generatorVersion": GENERATOR_VERSION,
        "nodeSchema": NODE_SCHEMA,
        "valueTypes": value_types,
        "valueTypesByKind": {
            "enum": value_types_for("enum"),
            "int": value_types_for("int"),
            "float": value_types_for("float"),
        },
        "cropPurposes": list(CROP_PURPOSES),
        "metaFields": list(META_FIELDS),
        "nodeClassTypes": sorted(NODE_CLASS_MAPPINGS.keys()),
        "workflowIoInputClassTypes": input_nodes,
        "workflowIoOutputClassTypes": output_nodes,
        "nodeDisplayNames": dict(sorted(NODE_DISPLAY_NAME_MAPPINGS.items())),
        "semanticExportFields": SEMANTIC_EXPORT_FIELDS,
    }


def ts_string_literal(value: str) -> str:
    return json.dumps(value)


def ts_union(values: list[str]) -> str:
    if not values:
        return "never"
    return " | ".join(ts_string_literal(v) for v in values)


def render_typescript(contract: dict) -> str:
    value_type_names = [entry["name"] for entry in contract["valueTypes"]]
    value_types_const = {
        entry["name"]: {"kinds": entry["kinds"], "description": entry["description"]}
        for entry in contract["valueTypes"]
    }
    lines = [
        "/** Generated by scripts/generate_workflow_io_contract.py — do not edit. */",
        "",
        f"export const WORKFLOW_IO_NODE_SCHEMA = {ts_string_literal(contract['nodeSchema'])} as const;",
        "",
        f"export type WorkflowIoValueType = {ts_union(value_type_names)};",
        f"export type WorkflowIoValueTypeEnum = {ts_union(contract['valueTypesByKind']['enum'])};",
        f"export type WorkflowIoValueTypeInt = {ts_union(contract['valueTypesByKind']['int'])};",
        f"export type WorkflowIoValueTypeFloat = {ts_union(contract['valueTypesByKind']['float'])};",
        "",
        f"export type WorkflowIoCropPurpose = {ts_union(contract['cropPurposes'])};",
        "",
        f"export type WorkflowIoMetaField = {ts_union(contract['metaFields'])};",
        "",
        f"export type WorkflowIoNodeClassType = {ts_union(contract['nodeClassTypes'])};",
        f"export type WorkflowIoInputClassType = {ts_union(contract['workflowIoInputClassTypes'])};",
        f"export type WorkflowIoOutputClassType = {ts_union(contract['workflowIoOutputClassTypes'])};",
        "",
        "export const WORKFLOW_IO_VALUE_TYPES = "
        + json.dumps(value_types_const, indent=2)
        + " as const satisfies Record<"
        "WorkflowIoValueType, { kinds: readonly string[]; description: string }>;",
        "",
        f"export const WORKFLOW_IO_CROP_PURPOSES = {json.dumps(contract['cropPurposes'])} as const;",
        "",
        f"export const WORKFLOW_IO_INPUT_CLASS_TYPES = {json.dumps(contract['workflowIoInputClassTypes'])} as const;",
        "",
        "/** Optional semantic fields a node's exported inputs may carry (api_config / mappings). */",
        "export const WORKFLOW_IO_SEMANTIC_EXPORT_FIELDS = "
        + json.dumps(contract["semanticExportFields"], indent=2)
        + " as const;",
        "",
        "export const WORKFLOW_IO_CONTRACT = "
        + json.dumps(
            {
                "generatorVersion": contract["generatorVersion"],
                "nodeSchema": contract["nodeSchema"],
            },
            indent=2,
        )
        + " as const;",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=REPO_ROOT / "dist",
        help="Write workflow-io-contract.ts here (default: dist/)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit 1 if outputs on disk differ from a fresh generation",
    )
    args = parser.parse_args()

    contract = build_contract()
    out_dir = args.out_dir
    ts_path = out_dir / "workflow-io-contract.ts"
    ts_text = render_typescript(contract)

    if args.check:
        if not ts_path.is_file() or ts_path.read_text() != ts_text:
            print(
                "Contract output is stale; run: python3 scripts/generate_workflow_io_contract.py",
                file=sys.stderr,
            )
            print(f"  - {ts_path.name}", file=sys.stderr)
            return 1
        print("Contract output is up to date.")
        return 0

    out_dir.mkdir(parents=True, exist_ok=True)
    ts_path.write_text(ts_text)
    print(f"Wrote {ts_path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())